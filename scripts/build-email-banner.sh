#!/usr/bin/env bash
# Builds the two small banner images from the dragon-and-d20 hero art:
#   - backend/src/consts/emailBanner.ts  (600x200 JPEG, embedded in sign-in/reset emails as a CID attachment)
#   - web/public/og-banner.jpg           (1100x576 JPEG, the link-preview image for invite links)
# Why JPEG: Outlook and some Gmail views do not render WebP. Why generated into a TS constant: the
# banner then ships inside the compiled backend, native or container, with no file to find at runtime.
# Re-run after changing the hero art. Needs ImageMagick (`magick`).
set -euo pipefail
cd "$(dirname "$0")/.."

command -v magick >/dev/null || { echo "ImageMagick (magick) is required" >&2; exit 1; }

SRC=web/src/assets/hero-1100.webp
EMAIL_OUT=backend/src/consts/emailBanner.ts
OG_OUT=web/public/og-banner.jpg
EMAIL_MAX=36000
OG_MAX=120000

# Steps quality down until the file fits the budget.
shrink() { # <crop> <resize> <max-bytes> <out>
  local q
  for q in 80 72 64 56 48 40; do
    magick "$SRC" -crop "$1" +repage -resize "$2" -strip -interlace Plane \
      -sampling-factor 4:2:0 -quality "$q" "$4"
    [ "$(stat -c %s "$4")" -le "$3" ] && return 0
  done
  echo "could not get $4 under $3 bytes" >&2
  exit 1
}

tmp=$(mktemp --suffix=.jpg)
trap 'rm -f "$tmp"' EXIT

# A 3:1 band around the dragon's head and the d20.
shrink "${EMAIL_CROP:-1100x367+0+130}" 600x200! "$EMAIL_MAX" "$tmp"
{
  echo "// Generated by scripts/build-email-banner.sh from web/src/assets/hero-1100.webp. Do not edit."
  echo "/** The Content-ID the email HTML refers to as cid:vtt-banner. */"
  echo "export const EMAIL_BANNER_CID = 'vtt-banner';"
  echo
  echo "/** A 600x200 JPEG, $(stat -c %s "$tmp") bytes. */"
  echo "export const EMAIL_BANNER_JPEG_BASE64 ="
  echo "  '$(base64 -w0 "$tmp")';"
} >"$EMAIL_OUT"

shrink "${OG_CROP:-1100x576+0+20}" 1100x576! "$OG_MAX" "$OG_OUT"
echo "wrote $EMAIL_OUT ($(stat -c %s "$tmp") bytes of JPEG) and $OG_OUT ($(stat -c %s "$OG_OUT") bytes)"
