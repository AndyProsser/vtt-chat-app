#!/usr/bin/env bash
# Generates infra/compose/.env and livekit.yaml with fresh random secrets. Safe to re-run: existing
# files are left alone unless you pass --force. Secrets are written straight to files (mode 600)
# and never printed.
#
#   ./setup.sh <site-address> [public-ip]
#     site-address  the hostname players will use, e.g. vtt.example.com (or "localhost" to try it out)
#     VALKEY_HOST_PORT (env) loopback port LiveKit uses for Valkey, default 6379
#     public-ip     set when the server is behind NAT and LiveKit must advertise its public address
set -euo pipefail
cd "$(dirname "$0")"

force=0
args=()
for a in "$@"; do if [[ $a == --force ]]; then force=1; else args+=("$a"); fi; done
site="${args[0]:-}"
public_ip="${args[1]:-}"
# LiveKit is host-networked, so it reaches Valkey through a loopback port on the host. Override if 6379 is taken.
valkey_port="${VALKEY_HOST_PORT:-6379}"
[[ -n $site ]] || { echo "usage: $0 <site-address> [public-ip] [--force]" >&2; exit 2; }

if [[ -e .env && $force -eq 0 ]]; then
  echo ".env already exists; leaving it (use --force to regenerate, which invalidates all sessions and tokens)"
  exit 0
fi

# hex of N random bytes (avoids a `head` closing a pipe early, which pipefail would turn into a failure)
rand() { openssl rand -hex "$1"; }

umask 077
lk_key="API$(rand 6)"
lk_secret="$(rand 32)"
{
  echo "SITE_ADDRESS=$site"
  echo "POSTGRES_PASSWORD=$(rand 16)"
  echo "LIVEKIT_API_KEY=$lk_key"
  echo "LIVEKIT_API_SECRET=$lk_secret"
  echo "VALKEY_HOST_PORT=$valkey_port"
} > .env

use_external_ip=false
[[ -n $public_ip ]] && use_external_ip=true
cat > livekit.yaml <<YAML
# Generated by setup.sh — do not commit. Host-networked LiveKit (see compose.yml).
port: 7880
bind_addresses:
  - ''
rtc:
  tcp_port: 7881        # ICE-over-TCP fallback
  port_range_start: 50000
  port_range_end: 50200 # forward this UDP range to the server; widen for large groups
  use_external_ip: $use_external_ip
redis:
  address: 127.0.0.1:$valkey_port
keys:
  $lk_key: $lk_secret
YAML
echo "Wrote .env and livekit.yaml for $site. Next: docker compose up -d --build"
[[ $force -eq 1 ]] && echo "NOTE: Postgres keeps the password it was first started with. If the stack has run before, regenerating means \`docker compose down -v\`, which DELETES the database."
echo "Open to the internet: 80/tcp, 443/tcp+udp, 7881/tcp, 50000-50200/udp."
