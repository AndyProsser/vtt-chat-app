/** An icon for each special sense, so a hover card can show "Darkvision 60" as a moon and a small number. */
export const SENSE_ICON: Record<SenseKind, LucideIcon> = {
  darkvision: ICON.moon,
  blindsight: ICON.radar,
  tremorsense: ICON.waves,
  truesight: ICON.scanEye,
};

/** The three quick numbers on a character: armour class, hit points and passive perception. */
export const VITAL_ICON = {
  ac: ICON.shield,
  hp: ICON.heart,
  pp: ICON.eye,
} as const satisfies Record<'ac' | 'hp' | 'pp', LucideIcon>;

